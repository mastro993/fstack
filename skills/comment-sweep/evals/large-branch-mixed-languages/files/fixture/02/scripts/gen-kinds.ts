import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

type Kind = { label: string; channels: string[] };

const kinds = parse(readFileSync("notification-kinds.yaml", "utf8")) as Record<string, Kind>;
const names = Object.keys(kinds);
const q = (s: string) => JSON.stringify(s);

const out = `// Code generated by scripts/gen-kinds.ts from notification-kinds.yaml. DO NOT EDIT.

${names.map((n) => `// Kind: ${n}`).join("\n")}

export const NOTIFICATION_KINDS = [
${names.map((n) => `  ${q(n)},`).join("\n")}
] as const;

export type NotificationKind = (typeof NOTIFICATION_KINDS)[number];

// Default channels per kind
export const DEFAULT_CHANNELS: Record<NotificationKind, readonly ("EMAIL" | "PUSH" | "WEBHOOK")[]> = {
${names.map((n) => `  // ${n}\n  ${q(n)}: [${kinds[n].channels.map(q).join(", ")}],`).join("\n")}
};

// Human-readable labels
export const KIND_LABELS: Record<NotificationKind, string> = {
${names.map((n) => `  ${q(n)}: ${q(kinds[n].label)},`).join("\n")}
};

export function isNotificationKind(value: string): value is NotificationKind {
  // Linear scan over the list
  return (NOTIFICATION_KINDS as readonly string[]).includes(value);
}
`;

writeFileSync("src/generated/notification-kinds.ts", out);
